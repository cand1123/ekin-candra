-- 1. TABEL: users
CREATE TABLE IF NOT EXISTS public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama VARCHAR(255) NOT NULL,
    email VARCHAR(255) DEFAULT NULL,
    google_id VARCHAR(255) DEFAULT NULL,
    auth_provider VARCHAR(50) NOT NULL DEFAULT 'local' CHECK (auth_provider IN ('local', 'google')),
    nip VARCHAR(50) NOT NULL,
    jabatan VARCHAR(255) NOT NULL,
    unit_kerja VARCHAR(255) NOT NULL,
    instansi VARCHAR(255) NOT NULL,
    username VARCHAR(100) NOT NULL UNIQUE,
    password VARCHAR(255) DEFAULT NULL,
    foto VARCHAR(512) DEFAULT NULL,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_users_email ON public.users(email);
CREATE INDEX IF NOT EXISTS idx_users_google_id ON public.users(google_id);

-- 2. TABEL: rencana_hasil_kerja
CREATE TABLE IF NOT EXISTS public.rencana_hasil_kerja (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE ON UPDATE CASCADE,
    nama_rhk VARCHAR(255) NOT NULL,
    indikator TEXT NOT NULL,
    target VARCHAR(255) NOT NULL,
    output VARCHAR(255) NOT NULL,
    tahun SMALLINT NOT NULL,
    bulan SMALLINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_rhk_user ON public.rencana_hasil_kerja(user_id);
CREATE INDEX IF NOT EXISTS idx_rhk_tahun ON public.rencana_hasil_kerja(user_id, tahun);
CREATE INDEX IF NOT EXISTS idx_rhk_bulan_tahun ON public.rencana_hasil_kerja(user_id, bulan, tahun);

-- 3. TABEL: laporan_harian
CREATE TABLE IF NOT EXISTS public.laporan_harian (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE ON UPDATE CASCADE,
    rhk_id BIGINT NULL REFERENCES public.rencana_hasil_kerja(id) ON DELETE SET NULL ON UPDATE CASCADE,
    tanggal DATE NOT NULL,
    uraian_kegiatan TEXT NOT NULL,
    jam_mulai TIME NOT NULL DEFAULT '07:30:00',
    jam_selesai TIME NOT NULL DEFAULT '16:00:00',
    jumlah_kegiatan INT NOT NULL DEFAULT 1,
    hasil TEXT NULL DEFAULT NULL,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_lh_user ON public.laporan_harian(user_id);
CREATE INDEX IF NOT EXISTS idx_lh_tanggal ON public.laporan_harian(tanggal);
CREATE INDEX IF NOT EXISTS idx_lh_user_tanggal ON public.laporan_harian(user_id, tanggal);
CREATE INDEX IF NOT EXISTS idx_lh_rhk ON public.laporan_harian(rhk_id);

-- 4. TABEL: rencana_aksi
CREATE TABLE IF NOT EXISTS public.rencana_aksi (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rhk_id BIGINT NOT NULL REFERENCES public.rencana_hasil_kerja(id) ON DELETE CASCADE ON UPDATE CASCADE,
    bulan SMALLINT NOT NULL,
    tahun SMALLINT NOT NULL,
    indikator TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    CONSTRAINT uk_ra_rhk_bulan_tahun UNIQUE (rhk_id, bulan, tahun)
);

CREATE INDEX IF NOT EXISTS idx_ra_rhk ON public.rencana_aksi(rhk_id);

-- 5. TABEL: rhk_bulanan_capaian
CREATE TABLE IF NOT EXISTS public.rhk_bulanan_capaian (
    user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE ON UPDATE CASCADE,
    rhk_id BIGINT NOT NULL REFERENCES public.rencana_hasil_kerja(id) ON DELETE CASCADE ON UPDATE CASCADE,
    bulan SMALLINT NOT NULL,
    tahun SMALLINT NOT NULL,
    output_hasil TEXT NULL,
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    PRIMARY KEY (user_id, rhk_id, bulan, tahun)
);

CREATE INDEX IF NOT EXISTS idx_capaian_user_tahun ON public.rhk_bulanan_capaian(user_id, tahun, bulan);
CREATE INDEX IF NOT EXISTS idx_capaian_rhk ON public.rhk_bulanan_capaian(rhk_id);

-- 6. TABEL: bukti_kegiatan
CREATE TABLE IF NOT EXISTS public.bukti_kegiatan (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    laporan_id BIGINT NOT NULL REFERENCES public.laporan_harian(id) ON DELETE CASCADE ON UPDATE CASCADE,
    user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE ON UPDATE CASCADE,
    nama_file VARCHAR(512) NOT NULL,
    path_file VARCHAR(512) NOT NULL,
    mime_type VARCHAR(50) DEFAULT NULL,
    ukuran_file BIGINT DEFAULT NULL,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_bk_laporan ON public.bukti_kegiatan(laporan_id);
CREATE INDEX IF NOT EXISTS idx_bk_user ON public.bukti_kegiatan(user_id);
CREATE INDEX IF NOT EXISTS idx_bk_laporan_user ON public.bukti_kegiatan(laporan_id, user_id);

-- TRIGGER UNTUK UPDATE OTOMATIS updated_at
CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = timezone('utc'::text, now());
    RETURN NEW;
END;
$$ language 'plpgsql';

DROP TRIGGER IF EXISTS trg_update_rencana_aksi_updated_at ON public.rencana_aksi;
CREATE TRIGGER trg_update_rencana_aksi_updated_at
    BEFORE UPDATE ON public.rencana_aksi
    FOR EACH ROW
    EXECUTE FUNCTION update_updated_at_column();

DROP TRIGGER IF EXISTS trg_update_rhk_bulanan_capaian_updated_at ON public.rhk_bulanan_capaian;
CREATE TRIGGER trg_update_rhk_bulanan_capaian_updated_at
    BEFORE UPDATE ON public.rhk_bulanan_capaian
    FOR EACH ROW
    EXECUTE FUNCTION update_updated_at_column();

