<?php
/**
 * Menerjemahkan SQL MySQL yang sudah ada ke PostgreSQL
 * dan menyediakan objek $mysqli yang dipakai seluruh halaman.
 */

function asn_mysql_to_pg($sql)
{
    $sql = trim((string)$sql);

    if (preg_match("/^SHOW\\s+TABLES\\s+LIKE\\s+'([^']*)'\\s*$/i", $sql, $m)) {
        $name = str_replace("'", "''", $m[1]);
        return "SELECT table_name FROM information_schema.tables WHERE table_schema = 'public' AND table_name = '{$name}'";
    }

    if (preg_match('/^DESCRIBE\\s+`?([a-zA-Z0-9_]+)`?\\s*$/i', $sql, $m)) {
        $name = $m[1];
        return 'SELECT column_name AS "Field", data_type AS "Type" FROM information_schema.columns WHERE table_schema = \'public\' AND table_name = \'' . $name . '\' ORDER BY ordinal_position';
    }

    if (preg_match('/^DELETE\\s+([a-zA-Z_][a-zA-Z0-9_]*)\\s+FROM\\s+([a-zA-Z_][a-zA-Z0-9_]*)\\s+\\1\\s+INNER\\s+JOIN\\s+(.+)$/is', $sql, $m)) {
        if (preg_match('/^(.+?)\\s+ON\\s+(.+?)\\s+WHERE\\s+(.+)$/is', $m[3], $j)) {
            $sql = 'DELETE FROM ' . $m[2] . ' ' . $m[1] . ' USING ' . trim($j[1]) . ' WHERE ' . trim($j[2]) . ' AND ' . trim($j[3]);
        }
    }

    if (stripos($sql, 'ON DUPLICATE KEY UPDATE') !== false) {
        $conflict = null;
        if (stripos($sql, 'rhk_bulanan_capaian') !== false) {
            $conflict = '(user_id, rhk_id, bulan, tahun)';
        } elseif (stripos($sql, 'rencana_aksi') !== false) {
            $conflict = '(rhk_id, bulan, tahun)';
        }
        if ($conflict !== null) {
            $sql = preg_replace('/ON\\s+DUPLICATE\\s+KEY\\s+UPDATE/i', 'ON CONFLICT ' . $conflict . ' DO UPDATE SET', $sql);
            $sql = preg_replace('/\\bVALUES\\s*\\(\\s*([a-zA-Z_][a-zA-Z0-9_]*)\\s*\\)/', 'EXCLUDED.$1', $sql);
        }
    }

    if (preg_match('/^ALTER\\s+TABLE\\s+([a-zA-Z0-9_]+)\\s+ADD\\s+INDEX\\s+IF\\s+NOT\\s+EXISTS\\s+([a-zA-Z0-9_]+)\\s*(\\([^)]+\\))\\s*$/i', $sql, $m)) {
        $sql = 'CREATE INDEX IF NOT EXISTS ' . $m[2] . ' ON ' . $m[1] . ' ' . $m[3];
    }

    if (preg_match('/^ALTER\\s+TABLE\\s+([a-zA-Z0-9_]+)\\s+MODIFY\\s+COLUMN\\s+([a-zA-Z0-9_]+)\\s+(.+)$/is', $sql, $m)) {
        if (stripos($m[3], 'NULL') !== false) {
            $sql = 'ALTER TABLE ' . $m[1] . ' ALTER COLUMN ' . $m[2] . ' DROP NOT NULL';
        }
    }

    $sql = preg_replace('/\\bISNULL\\s*\\(\\s*([^)]+)\\s*\\)/i', '($1 IS NULL)', $sql);
    $sql = preg_replace('/\\bMONTH\\s*\\(\\s*([^)]+)\\s*\\)/i', 'EXTRACT(MONTH FROM $1)', $sql);
    $sql = preg_replace('/\\bYEAR\\s*\\(\\s*([^)]+)\\s*\\)/i', 'EXTRACT(YEAR FROM $1)', $sql);
    $sql = preg_replace('/\\bIFNULL\\s*\\(/i', 'COALESCE(', $sql);

    $sql = preg_replace("/\\s+AFTER\\s+[a-zA-Z0-9_]+/i", '', $sql);
    $sql = preg_replace("/\\s+COMMENT\\s+'[^']*'/i", '', $sql);
    $sql = preg_replace('/\\s+ENGINE\\s*=\\s*\\w+/i', '', $sql);
    $sql = preg_replace('/\\s+DEFAULT\\s+CHARSET\\s*=\\s*\\w+/i', '', $sql);
    $sql = preg_replace('/\\s+COLLATE\\s*=?\\s*[\\w]+/i', '', $sql);
    $sql = preg_replace('/\\s+ON\\s+UPDATE\\s+CURRENT_TIMESTAMP/i', '', $sql);
    $sql = preg_replace('/\\bTINYINT\\b/i', 'SMALLINT', $sql);
    $sql = preg_replace('/\\bYEAR\\s+NOT\\s+NULL\\b/i', 'SMALLINT NOT NULL', $sql);
    $sql = preg_replace('/ENUM\\s*\\([^)]*\\)/i', 'VARCHAR(50)', $sql);
    $sql = str_replace('`', '', $sql);
    $sql = preg_replace('/\\bAUTO_INCREMENT\\b/i', 'GENERATED BY DEFAULT AS IDENTITY', $sql);

    return trim($sql);
}

function asn_pg_prepare_sql($sql, $types)
{
    $sql = asn_mysql_to_pg($sql);

    if (preg_match('/^\\s*INSERT\\s+INTO\\s+([a-zA-Z0-9_]+)\\b/i', $sql, $m) && stripos($sql, 'RETURNING') === false) {
        $table = strtolower($m[1]);
        $withId = ['users', 'rencana_hasil_kerja', 'laporan_harian', 'rencana_aksi', 'bukti_kegiatan'];
        if (in_array($table, $withId, true)) {
            $sql .= ' RETURNING id';
        }
    }

    $out = '';
    $n = 0;
    $len = strlen($sql);
    $inString = false;
    for ($i = 0; $i < $len; $i++) {
        $c = $sql[$i];
        if ($inString) {
            $out .= $c;
            if ($c === "'") {
                if ($i + 1 < $len && $sql[$i + 1] === "'") {
                    $out .= $sql[++$i];
                } else {
                    $inString = false;
                }
            }
            continue;
        }
        if ($c === "'") {
            $inString = true;
            $out .= $c;
            continue;
        }
        if ($c === '?') {
            $t = $types[$n] ?? 's';
            $n++;
            if ($t === 'i') {
                $out .= '$' . $n . '::int';
            } elseif ($t === 'd') {
                $out .= '$' . $n . '::float8';
            } else {
                $out .= '$' . $n;
            }
            continue;
        }
        $out .= $c;
    }

    return $out;
}

class AsnPgResult
{
    public $num_rows = 0;
    private $rows = [];
    private $index = 0;

    public function __construct($pgResult)
    {
        if (!$pgResult) {
            return;
        }
        $this->num_rows = pg_num_rows($pgResult);
        while ($row = pg_fetch_assoc($pgResult)) {
            $this->rows[] = $row;
        }
    }

    public function fetch_assoc()
    {
        if ($this->index >= count($this->rows)) {
            return null;
        }
        return $this->rows[$this->index++];
    }

    public function fetch_row()
    {
        $row = $this->fetch_assoc();
        if ($row === null) {
            return null;
        }
        return array_values($row);
    }

    public function cell($rowIndex, $column)
    {
        if (!isset($this->rows[$rowIndex])) {
            return null;
        }
        $row = $this->rows[$rowIndex];
        if (array_key_exists($column, $row)) {
            return $row[$column];
        }
        $values = array_values($row);
        return $values[$column] ?? null;
    }

    public function data_seek($offset)
    {
        $offset = (int)$offset;
        if ($offset < 0 || $offset > count($this->rows)) {
            return false;
        }
        $this->index = $offset;
        return true;
    }

    public function free()
    {
        $this->rows = [];
        $this->index = 0;
        $this->num_rows = 0;
    }
}

class AsnPgStatement
{
    public $num_rows = 0;
    public $error = '';
    private $db;
    private $sql;
    private $types = '';
    private $params = [];
    private $bound = [];
    private $result = null;
    private $parent;

    public function __construct($db, $sql, $parent)
    {
        $this->db = $db;
        $this->sql = $sql;
        $this->parent = $parent;
    }

    public function bind_param($types, &...$vars)
    {
        $this->types = (string)$types;
        $this->params = [];
        foreach ($vars as $i => &$var) {
            $this->params[$i] = &$var;
        }
        return true;
    }

    public function execute()
    {
        $values = [];
        foreach ($this->params as $i => &$value) {
            $type = $this->types[$i] ?? 's';
            if ($value === null) {
                $values[] = null;
            } elseif ($type === 'i') {
                $values[] = (string)(int)$value;
            } elseif ($type === 'd') {
                $values[] = (string)(float)$value;
            } else {
                $values[] = (string)$value;
            }
        }
        unset($value);

        $sql = asn_pg_prepare_sql($this->sql, $this->types);
        if (count($values) === 0) {
            $res = @pg_query($this->db, $sql);
        } else {
            $res = @pg_query_params($this->db, $sql, $values);
        }

        if ($res === false) {
            $this->error = pg_last_error($this->db);
            $this->parent->error = $this->error;
            $this->parent->errno = 1;
            return false;
        }

        $this->parent->affected_rows = pg_affected_rows($res);
        $this->parent->error = '';
        $this->parent->errno = 0;
        $this->error = '';

        if (pg_result_status($res) === PGSQL_TUPLES_OK) {
            $this->result = new AsnPgResult($res);
            $this->num_rows = $this->result->num_rows;
            if (stripos($sql, 'RETURNING id') !== false && $this->num_rows > 0) {
                $id = $this->result->cell(0, 'id');
                if ($id !== null && $id !== '') {
                    $this->parent->insert_id = (int)$id;
                }
            }
            return true;
        }

        $this->result = null;
        $this->num_rows = 0;
        return true;
    }

    public function get_result()
    {
        return $this->result ?: new AsnPgResult(null);
    }

    public function store_result()
    {
        return true;
    }

    public function bind_result(&...$vars)
    {
        $this->bound = [];
        foreach ($vars as $i => &$var) {
            $this->bound[$i] = &$var;
        }
        return true;
    }

    public function fetch()
    {
        if (!$this->result) {
            return false;
        }
        $row = $this->result->fetch_row();
        if ($row === null) {
            return null;
        }
        foreach ($this->bound as $i => &$target) {
            $target = $row[$i] ?? null;
        }
        unset($target);
        return true;
    }

    public function close()
    {
        $this->result = null;
        $this->params = [];
        $this->bound = [];
        return true;
    }
}

class AsnMysqli
{
    public $error = '';
    public $errno = 0;
    public $insert_id = 0;
    public $affected_rows = 0;
    public $connect_error = '';
    private $db;

    public function __construct($db)
    {
        $this->db = $db;
    }

    public function connection()
    {
        return $this->db;
    }

    public function query($sql)
    {
        $sqlPg = asn_pg_prepare_sql($sql, '');
        $res = @pg_query($this->db, $sqlPg);
        if ($res === false) {
            $this->error = pg_last_error($this->db);
            $this->errno = 1;
            return false;
        }
        $this->error = '';
        $this->errno = 0;
        $this->affected_rows = pg_affected_rows($res);
        if (pg_result_status($res) === PGSQL_TUPLES_OK) {
            $result = new AsnPgResult($res);
            if (stripos($sqlPg, 'RETURNING id') !== false && $result->num_rows > 0) {
                $id = $result->cell(0, 'id');
                if ($id !== null && $id !== '') {
                    $this->insert_id = (int)$id;
                }
            }
            return $result;
        }
        return true;
    }

    public function prepare($sql)
    {
        if (trim((string)$sql) === '') {
            $this->error = 'SQL kosong.';
            return false;
        }
        return new AsnPgStatement($this->db, $sql, $this);
    }

    public function begin_transaction()
    {
        $ok = @pg_query($this->db, 'BEGIN') !== false;
        if (!$ok) {
            $this->error = pg_last_error($this->db);
        }
        return $ok;
    }

    public function commit()
    {
        $ok = @pg_query($this->db, 'COMMIT') !== false;
        if (!$ok) {
            $this->error = pg_last_error($this->db);
        }
        return $ok;
    }

    public function rollback()
    {
        $ok = @pg_query($this->db, 'ROLLBACK') !== false;
        if (!$ok) {
            $this->error = pg_last_error($this->db);
        }
        return $ok;
    }

    public function real_escape_string($value)
    {
        return pg_escape_string($this->db, (string)$value);
    }

    public function close()
    {
        return true;
    }
}
